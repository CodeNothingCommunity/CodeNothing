//! CodeNothing Compiler
//! 
//! This module provides compilation functionality to generate
//! platform-independent bytecode files (.comcn)

use std::path::{Path, PathBuf};
use std::fs;

use crate::core::bytecode_file::ComcnFile;
use crate::lang::{Lexer, Parser, SemanticAnalyzer, CodeGenerator};

/// Compilation options
#[derive(Debug, Clone)]
pub struct CompileOptions {
    /// Output file path (if None, derives from input file)
    pub output: Option<PathBuf>,
    
    /// Optimization level (0-3)
    pub optimization_level: u8,
    
    /// Include debug information
    pub debug_info: bool,
    
    /// Verbose compilation output
    pub verbose: bool,
    
    /// Additional compilation flags
    pub flags: Vec<String>,
}

impl Default for CompileOptions {
    fn default() -> Self {
        Self {
            output: None,
            optimization_level: 0,
            debug_info: true,
            verbose: false,
            flags: Vec::new(),
        }
    }
}

/// Compilation result
#[derive(Debug)]
pub struct CompileResult {
    /// Output file path
    pub output_file: PathBuf,
    
    /// Compilation success
    pub success: bool,
    
    /// Compilation messages
    pub messages: Vec<String>,
    
    /// Generated bytecode file (if successful)
    pub bytecode: Option<ComcnFile>,
}

/// CodeNothing Compiler
pub struct Compiler {
    options: CompileOptions,
}

impl Compiler {
    /// Create a new compiler with default options
    pub fn new() -> Self {
        Self {
            options: CompileOptions::default(),
        }
    }
    
    /// Create a new compiler with custom options
    pub fn with_options(options: CompileOptions) -> Self {
        Self { options }
    }
    
    /// Compile a CodeNothing source file to bytecode
    pub fn compile<P: AsRef<Path>>(&self, input_file: P) -> CompileResult {
        let input_path = input_file.as_ref();
        let mut messages = Vec::new();
        
        if self.options.verbose {
            messages.push(format!("Compiling: {}", input_path.display()));
        }
        
        // Determine output file path
        let output_path = self.options.output.clone().unwrap_or_else(|| {
            let mut path = input_path.to_path_buf();
            path.set_extension("comcn");
            path
        });
        
        // Read source file
        let source = match fs::read_to_string(input_path) {
            Ok(content) => content,
            Err(e) => {
                messages.push(format!("Error reading file: {}", e));
                return CompileResult {
                    output_file: output_path,
                    success: false,
                    messages,
                    bytecode: None,
                };
            }
        };
        
        if self.options.verbose {
            messages.push("1. Lexical analysis...".to_string());
        }
        
        // Lexical analysis
        let mut lexer = Lexer::new(&source);
        let tokens = match lexer.tokenize() {
            Ok(tokens) => {
                if self.options.verbose {
                    messages.push(format!("   Generated {} tokens", tokens.len()));
                }
                tokens
            }
            Err(e) => {
                messages.push(format!("Lexical error: {:?}", e));
                return CompileResult {
                    output_file: output_path,
                    success: false,
                    messages,
                    bytecode: None,
                };
            }
        };
        
        if self.options.verbose {
            messages.push("2. Syntax analysis...".to_string());
        }
        
        // Syntax analysis
        let mut parser = Parser::new(tokens);
        let ast = match parser.parse_program() {
            Ok(ast) => {
                if self.options.verbose {
                    messages.push(format!("   Parsed {} declarations", ast.declarations.len()));
                }
                ast
            }
            Err(e) => {
                messages.push(format!("Syntax error: {:?}", e));
                return CompileResult {
                    output_file: output_path,
                    success: false,
                    messages,
                    bytecode: None,
                };
            }
        };
        
        if self.options.verbose {
            messages.push("3. Semantic analysis...".to_string());
        }
        
        // Semantic analysis
        let mut analyzer = SemanticAnalyzer::new();
        if let Err(semantic_errors) = analyzer.analyze_program(&ast) {
            messages.push("Semantic errors:".to_string());
            for error in &semantic_errors {
                messages.push(format!("  {}", error));
            }
            return CompileResult {
                output_file: output_path,
                success: false,
                messages,
                bytecode: None,
            };
        }

        // Double check for any additional errors
        if !analyzer.get_errors().is_empty() {
            messages.push("Additional semantic errors:".to_string());
            for error in analyzer.get_errors() {
                messages.push(format!("  {}", error));
            }
            return CompileResult {
                output_file: output_path,
                success: false,
                messages,
                bytecode: None,
            };
        }
        
        if self.options.verbose {
            messages.push("   Type checking completed successfully".to_string());
        }
        
        if self.options.verbose {
            messages.push("4. Code generation...".to_string());
        }

        println!("🔧 Compiler: Entering code generation phase");

        // Use catch_unwind to capture any panics during code generation
        let code_gen_result = std::panic::catch_unwind(|| {
            println!("🔧 Compiler: About to create code generator");

            // Code generation
            let mut generator = CodeGenerator::new();
            println!("🔧 Compiler: Code generator created successfully");

            generator.set_debug_mode(self.options.verbose);
            println!("🔧 Compiler: Debug mode set");

            generator.set_type_environment(analyzer.get_type_environment().clone());
            println!("🔧 Compiler: Type environment set");

            // Debug: Check external modules (always show for debugging)
            let external_modules = analyzer.get_external_modules();
            println!("🔧 Compiler: Found {} external modules (verbose={})", external_modules.len(), self.options.verbose);
            for (module_path, external_program) in external_modules {
                println!("🔧 Compiler: External module '{}' has {} declarations", module_path, external_program.declarations.len());
            }

            generator
        });

        let mut generator = match code_gen_result {
            Ok(gen) => {
                println!("🔧 Compiler: Code generation setup completed successfully");
                gen
            },
            Err(e) => {
                println!("🔧 Compiler: PANIC during code generation setup: {:?}", e);
                messages.push("Error: Code generation setup failed due to panic".to_string());
                return CompileResult {
                    output_file: output_path,
                    success: false,
                    messages,
                    bytecode: None,
                };
            }
        };
        println!("🔧 Compiler: Code generator created successfully");

        generator.set_debug_mode(self.options.verbose);
        println!("🔧 Compiler: Debug mode set");

        generator.set_type_environment(analyzer.get_type_environment().clone());
        println!("🔧 Compiler: Type environment set");

        // Debug: Check external modules (always show for debugging)
        let external_modules = analyzer.get_external_modules();
        println!("🔧 Compiler: Found {} external modules (verbose={})", external_modules.len(), self.options.verbose);
        for (module_path, external_program) in external_modules {
            println!("🔧 Compiler: External module '{}' has {} declarations", module_path, external_program.declarations.len());
        }

        // First, collect and compile all external module functions
        for (module_path, external_program) in analyzer.get_external_modules() {
            if self.options.verbose {
                println!("🔧 Compiler: Collecting functions from external module: {}", module_path);
            }
            // First pass: collect all functions from external module
            generator.collect_functions(external_program);
        }

        // Collect functions from main program
        if self.options.verbose {
            println!("🔧 Compiler: Collecting functions from main program");
        }
        generator.collect_functions(&ast);

        // Second pass: generate code for all external modules
        for (module_path, external_program) in analyzer.get_external_modules() {
            if self.options.verbose {
                println!("🔧 Compiler: Generating code for external module: {}", module_path);
            }
            let _ = generator.generate_program(external_program);
        }

        // Generate code for main program
        if self.options.verbose {
            println!("🔧 Compiler: Generating code for main program");
        }
        let _ = generator.generate_program(&ast);

        println!("🔧 Compiler: Checking for code generation errors...");
        if !generator.get_errors().is_empty() {
            println!("🔧 Compiler: Found {} code generation errors", generator.get_errors().len());
            messages.push("Code generation errors:".to_string());
            for error in generator.get_errors() {
                messages.push(format!("  {}", error));
            }
            return CompileResult {
                output_file: output_path,
                success: false,
                messages,
                bytecode: None,
            };
        }
        println!("🔧 Compiler: No code generation errors found");
        
        if self.options.verbose {
            messages.push(format!("   Generated {} chunks", generator.get_chunks().len()));
        }

        if self.options.verbose {
            messages.push("5. Creating bytecode file...".to_string());
        }

        // Create bytecode file
        let mut bytecode_file = ComcnFile::new(
            input_path.file_name()
                .and_then(|n| n.to_str())
                .unwrap_or("unknown")
                .to_string(),
            "main".to_string()
        );

        // Set compilation options in metadata
        bytecode_file.metadata.optimization_level = self.options.optimization_level;
        bytecode_file.metadata.debug_info = self.options.debug_info;
        bytecode_file.metadata.flags = self.options.flags.clone();

        // Add all chunks to bytecode file in the correct order
        // Get chunks as a vector to preserve the original compilation order
        let chunks_vec = generator.get_chunks_ordered();
        for (name, chunk) in chunks_vec {
            bytecode_file.add_chunk(name, chunk);
        }

        // Set class inheritance relationships
        bytecode_file.set_class_inheritance(generator.get_class_inheritance().clone());

        // Set class definitions
        bytecode_file.set_class_definitions(generator.get_class_definitions().clone());

        // Set memoized functions
        bytecode_file.set_memo_functions(generator.get_memo_functions().clone());

        // Set library dependencies
        bytecode_file.set_library_dependencies(generator.get_library_dependencies().clone());

        // Save bytecode file
        if let Err(e) = bytecode_file.save_to_file(&output_path) {
            messages.push(format!("Error saving bytecode file: {}", e));
            return CompileResult {
                output_file: output_path,
                success: false,
                messages,
                bytecode: None,
            };
        }
        
        if self.options.verbose {
            messages.push(format!("   Bytecode saved to: {}", output_path.display()));
        }
        
        messages.push("Compilation completed successfully!".to_string());
        
        CompileResult {
            output_file: output_path,
            success: true,
            messages,
            bytecode: Some(bytecode_file),
        }
    }
}
